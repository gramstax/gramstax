#!/usr/bin/env node
/**
 * Drop a fully opaque alpha channel from a PNG and re-deflate it.
 *
 * The rasterizer used for the OG assets (`@resvg/resvg-js-cli`) always writes
 * RGBA. Those cards are fully opaque, so the alpha byte of every pixel is the
 * constant 255 and carries no information. Dropping it turns the image from
 * colorType 6 into colorType 2 and roughly halves the file, which is why the
 * committed cards are RGB rather than whatever the rasterizer emitted. The two
 * are pixel-identical once composited: this is a size change, not a visual one.
 *
 * Without this step the committed PNGs cannot be reproduced, so the assets were
 * previously regenerated by hand and the exact operation lived nowhere. It lives
 * here now.
 *
 * Usage:
 *     node scripts/docs/flatten-png.mjs <in.png> <out.png>
 *
 * A PNG whose alpha channel is not entirely 255 is refused rather than
 * flattened: dropping it would be lossy, and losing translucency looks fine
 * until the image is composited over a non-white background.
 */

import {readFileSync, writeFileSync} from "node:fs";
import {deflateSync, inflateSync} from "node:zlib";

const SIGNATURE = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

const CRC_TABLE = (() => {
  const table = new Int32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[n] = c;
  }
  return table;
})();

/** @param {Buffer} buf @returns {number} */
function crc32(buf) {
  let c = 0xffffffff;
  for (const byte of buf) c = CRC_TABLE[(c ^ byte) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

/**
 * @param {string} type @param {Buffer} data @returns {Buffer}
 */
function chunk(type, data) {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length, 0);
  const body = Buffer.concat([Buffer.from(type, `ascii`), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body), 0);
  return Buffer.concat([length, body, crc]);
}

/** @param {Buffer} png @returns {{width: number, height: number, colorType: number, bitDepth: number, idat: Buffer}} */
function readPng(png) {
  if (!png.subarray(0, 8).equals(SIGNATURE)) throw new Error(`not a PNG`);
  const width = png.readUInt32BE(16);
  const height = png.readUInt32BE(20);
  const bitDepth = png[24];
  const colorType = png[25];
  const parts = [];
  let offset = 8;
  while (offset < png.length) {
    const length = png.readUInt32BE(offset);
    const type = png.toString(`ascii`, offset + 4, offset + 8);
    if (type === `IDAT`) parts.push(png.subarray(offset + 8, offset + 8 + length));
    if (type === `IEND`) break;
    offset += 12 + length;
  }
  return {width, height, colorType, bitDepth, idat: Buffer.concat(parts)};
}

/**
 * Reverse the per-row filter so the scanlines are plain pixel bytes.
 *
 * @param {Buffer} raw @param {number} width @param {number} height @param {number} bpp
 * @returns {Buffer}
 */
function unfilter(raw, width, height, bpp) {
  const stride = width * bpp;
  const out = Buffer.alloc(height * stride);
  let cursor = 0;
  for (let y = 0; y < height; y++) {
    const filter = raw[cursor++];
    for (let x = 0; x < stride; x++) {
      const value = raw[cursor + x];
      const left = x >= bpp ? out[y * stride + x - bpp] : 0;
      const up = y > 0 ? out[(y - 1) * stride + x] : 0;
      const upLeft = x >= bpp && y > 0 ? out[(y - 1) * stride + x - bpp] : 0;
      let restored;
      if (filter === 0) restored = value;
      else if (filter === 1) restored = value + left;
      else if (filter === 2) restored = value + up;
      else if (filter === 3) restored = value + ((left + up) >> 1);
      else if (filter === 4) {
        const p = left + up - upLeft;
        const da = Math.abs(p - left);
        const db = Math.abs(p - up);
        const dc = Math.abs(p - upLeft);
        restored = value + (da <= db && da <= dc ? left : db <= dc ? up : upLeft);
      } else throw new Error(`unknown filter type ${filter} on row ${y}`);
      out[y * stride + x] = restored & 0xff;
    }
    cursor += stride;
  }
  return out;
}

/**
 * Re-apply the standard minimum-sum-of-absolute-differences filter heuristic.
 *
 * @param {Buffer} pixels @param {number} width @param {number} height @param {number} bpp
 * @returns {Buffer}
 */
function filter(pixels, width, height, bpp) {
  const stride = width * bpp;
  const out = Buffer.alloc(height * (stride + 1));
  const candidate = Buffer.alloc(stride);
  const best = Buffer.alloc(stride);
  for (let y = 0; y < height; y++) {
    const row = pixels.subarray(y * stride, y * stride + stride);
    const prior = y > 0 ? pixels.subarray((y - 1) * stride, (y - 1) * stride + stride) : null;
    let bestFilter = 0;
    let bestScore = Infinity;
    for (let type = 0; type < 5; type++) {
      let score = 0;
      for (let x = 0; x < stride; x++) {
        const left = x >= bpp ? row[x - bpp] : 0;
        const up = prior ? prior[x] : 0;
        const upLeft = prior && x >= bpp ? prior[x - bpp] : 0;
        let value;
        if (type === 0) value = row[x];
        else if (type === 1) value = row[x] - left;
        else if (type === 2) value = row[x] - up;
        else if (type === 3) value = row[x] - ((left + up) >> 1);
        else {
          const p = left + up - upLeft;
          const da = Math.abs(p - left);
          const db = Math.abs(p - up);
          const dc = Math.abs(p - upLeft);
          value = row[x] - (da <= db && da <= dc ? left : db <= dc ? up : upLeft);
        }
        value &= 0xff;
        candidate[x] = value;
        score += value < 128 ? value : 256 - value;
      }
      if (score < bestScore) {
        bestScore = score;
        bestFilter = type;
        candidate.copy(best);
      }
    }
    out[y * (stride + 1)] = bestFilter;
    best.copy(out, y * (stride + 1) + 1);
  }
  return out;
}

const [input, output] = process.argv.slice(2);
if (!input || !output) {
  console.error(`usage: node scripts/docs/flatten-png.mjs <in.png> <out.png>`);
  process.exit(2);
}

const png = readPng(readFileSync(input));
if (png.bitDepth !== 8) throw new Error(`expected 8-bit, got ${png.bitDepth}`);
if (png.colorType !== 6) {
  if (png.colorType !== 2) throw new Error(`expected colorType 6 (RGBA) or 2 (RGB), got ${png.colorType}`);
  writeFileSync(output, readFileSync(input));
  console.log(`${input} is already RGB; copied to ${output}`);
  process.exit(0);
}

const rgba = unfilter(inflateSync(png.idat), png.width, png.height, 4);
for (let i = 3; i < rgba.length; i += 4) {
  if (rgba[i] !== 255) {
    throw new Error(`pixel ${(i - 3) / 4} has alpha ${rgba[i]}; flattening would lose transparency`);
  }
}

const rgb = Buffer.alloc((rgba.length / 4) * 3);
for (let src = 0, dst = 0; src < rgba.length; src += 4, dst += 3) {
  rgb[dst] = rgba[src];
  rgb[dst + 1] = rgba[src + 1];
  rgb[dst + 2] = rgba[src + 2];
}

const ihdr = Buffer.alloc(13);
ihdr.writeUInt32BE(png.width, 0);
ihdr.writeUInt32BE(png.height, 4);
ihdr[8] = 8;
ihdr[9] = 2;
ihdr[10] = 0;
ihdr[11] = 0;
ihdr[12] = 0;
const idat = deflateSync(filter(rgb, png.width, png.height, 3), {level: 9});

writeFileSync(output, Buffer.concat([SIGNATURE, chunk(`IHDR`, ihdr), chunk(`IDAT`, idat), chunk(`IEND`, Buffer.alloc(0))]));

const before = readFileSync(input).length;
const after = readFileSync(output).length;
console.log(
  `${input} -> ${output}: ${png.width}x${png.height}, ${before} bytes RGBA -> ${after} bytes RGB ` +
    `(${(100 * after) / before < 100 ? `-${(100 - (100 * after) / before).toFixed(0)}%` : `+${((100 * after) / before - 100).toFixed(0)}%`})`
);
