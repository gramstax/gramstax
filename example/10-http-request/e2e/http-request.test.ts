import {beforeEach, describe, expect, it} from "bun:test"
import {e2e, flowUser, flowUserId, httpServerUrl} from "./setup"

const intent = `http-request`
beforeEach(() => {
  e2e.clearCalls()
})
describe(`E2E: HttpRequestPage`, () => {
  it(`show method selection`, async () => {
    await e2e.sendText(`/start`, flowUser)
    await e2e.sendText(`/start`, flowUserId)
    e2e.clearCalls()
    const res = await e2e.sendCallbackQuery(intent, flowUser)
    const resId = await e2e.sendCallbackQuery(intent, flowUserId)
    expect(res[0]!.body?.text).toBe(e2e.gmsg(intent, `s-method`, {}))
    expect(resId[0]!.body?.text).toBe(e2e.gmsg(intent, `s-method`, {}, `id`))
  })
  it(`show URL input after method selected`, async () => {
    await e2e.sendText(`/start`, flowUser)
    await e2e.sendText(`/start`, flowUserId)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(intent, flowUser)
    await e2e.sendCallbackQuery(intent, flowUserId)
    e2e.clearCalls()
    const res = await e2e.sendCallbackQuery(`${intent}:GET`, flowUser)
    const resId = await e2e.sendCallbackQuery(`${intent}:GET`, flowUserId)
    expect(res.length).toBe(1)
    expect(resId.length).toBe(1)
    expect(res[0]!.body?.text).toBe(e2e.gmsg(intent, `s-url`, {method: `GET`}))
    expect(resId[0]!.body?.text).toBe(e2e.gmsg(intent, `s-url`, {method: `GET`}, `id`))
  })
  it(`makes HTTP request and shows response`, async () => {
    await e2e.sendText(`/start`, flowUser)
    await e2e.sendText(`/start`, flowUserId)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(intent, flowUser)
    await e2e.sendCallbackQuery(intent, flowUserId)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(`${intent}:GET`, flowUser)
    await e2e.sendCallbackQuery(`${intent}:GET`, flowUserId)
    e2e.clearCalls()
    await e2e.sendText(`${httpServerUrl}/test`, flowUser)
    await e2e.sendText(`${httpServerUrl}/test`, flowUserId)
    e2e.clearCalls()
    const res = await e2e.sendCallbackQuery(`${intent}:skip_token`, flowUser)
    const resId = await e2e.sendCallbackQuery(`${intent}:skip_token`, flowUserId)
    expect(res.length).toBeGreaterThan(0)
    expect(resId.length).toBeGreaterThan(0)
    expect(res[0]!.body?.text).toContain(`[GET]`)
    expect(res[0]!.body?.text).toContain(`200`)
    expect(res[0]!.body?.text).toContain(`Hello from test server`)
    expect(resId[0]!.body?.text).toContain(`[GET]`)
    expect(resId[0]!.body?.text).toContain(`200`)
    expect(resId[0]!.body?.text).toContain(`Hello from test server`)
  })
  it(`escapes HTML in response`, async () => {
    await e2e.sendText(`/start`, flowUser)
    await e2e.sendText(`/start`, flowUserId)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(intent, flowUser)
    await e2e.sendCallbackQuery(intent, flowUserId)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(`${intent}:GET`, flowUser)
    await e2e.sendCallbackQuery(`${intent}:GET`, flowUserId)
    e2e.clearCalls()
    await e2e.sendText(`${httpServerUrl}/html`, flowUser)
    await e2e.sendText(`${httpServerUrl}/html`, flowUserId)
    e2e.clearCalls()
    const res = await e2e.sendCallbackQuery(`${intent}:skip_token`, flowUser)
    const resId = await e2e.sendCallbackQuery(`${intent}:skip_token`, flowUserId)
    expect(res[0]!.body?.text).toContain(`&lt;h1&gt;`)
    expect(res[0]!.body?.text).not.toContain(`<h1>`)
    expect(resId[0]!.body?.text).toContain(`&lt;h1&gt;`)
    expect(resId[0]!.body?.text).not.toContain(`<h1>`)
  })
  it(`shows invalid URL warning`, async () => {
    await e2e.sendText(`/start`, flowUser)
    await e2e.sendText(`/start`, flowUserId)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(intent, flowUser)
    await e2e.sendCallbackQuery(intent, flowUserId)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(`${intent}:GET`, flowUser)
    await e2e.sendCallbackQuery(`${intent}:GET`, flowUserId)
    e2e.clearCalls()
    const res = await e2e.sendText(`not-a-valid-url`, flowUser)
    const resId = await e2e.sendText(`not-a-valid-url`, flowUserId)
    expect(res[0]!.body?.text).toBe(e2e.gmsg(intent, `w-invalid`, {url: `not-a-valid-url`}))
    expect(resId[0]!.body?.text).toBe(e2e.gmsg(intent, `w-invalid`, {url: `not-a-valid-url`}, `id`))
  })
  it(`completes POST with body and echo`, async () => {
    await e2e.sendText(`/start`, flowUser)
    await e2e.sendText(`/start`, flowUserId)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(intent, flowUser)
    await e2e.sendCallbackQuery(intent, flowUserId)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(`${intent}:POST`, flowUser)
    await e2e.sendCallbackQuery(`${intent}:POST`, flowUserId)
    e2e.clearCalls()
    await e2e.sendText(`${httpServerUrl}/echo`, flowUser)
    await e2e.sendText(`${httpServerUrl}/echo`, flowUserId)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(`${intent}:skip_token`, flowUser)
    await e2e.sendCallbackQuery(`${intent}:skip_token`, flowUserId)
    e2e.clearCalls()
    const res = await e2e.sendText(`{"hello":"world"}`, flowUser)
    const resId = await e2e.sendText(`{"hello":"world"}`, flowUserId)
    expect(res[0]!.body?.text).toContain(`[POST]`)
    expect(res[0]!.body?.text).toContain(`echoed`)
    expect(resId[0]!.body?.text).toContain(`[POST]`)
    expect(resId[0]!.body?.text).toContain(`echoed`)
  })
  it(`sends Bearer token in Authorization header`, async () => {
    await e2e.sendText(`/start`, flowUser)
    await e2e.sendText(`/start`, flowUserId)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(intent, flowUser)
    await e2e.sendCallbackQuery(intent, flowUserId)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(`${intent}:GET`, flowUser)
    await e2e.sendCallbackQuery(`${intent}:GET`, flowUserId)
    e2e.clearCalls()
    await e2e.sendText(`${httpServerUrl}/echo-headers`, flowUser)
    await e2e.sendText(`${httpServerUrl}/echo-headers`, flowUserId)
    e2e.clearCalls()
    const res = await e2e.sendText(`my-secret-token`, flowUser)
    const resId = await e2e.sendText(`my-secret-token`, flowUserId)
    expect(res[0]!.body?.text).toContain(`[GET]`)
    expect(res[0]!.body?.text).toContain(`Bearer my-secret-token`)
    expect(resId[0]!.body?.text).toContain(`[GET]`)
    expect(resId[0]!.body?.text).toContain(`Bearer my-secret-token`)
  })
  it(`toggles between formatted and raw JSON`, async () => {
    await e2e.sendText(`/start`, flowUser)
    await e2e.sendText(`/start`, flowUserId)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(intent, flowUser)
    await e2e.sendCallbackQuery(intent, flowUserId)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(`${intent}:GET`, flowUser)
    await e2e.sendCallbackQuery(`${intent}:GET`, flowUserId)
    e2e.clearCalls()
    await e2e.sendText(`${httpServerUrl}/test`, flowUser)
    await e2e.sendText(`${httpServerUrl}/test`, flowUserId)
    e2e.clearCalls()
    const skip = await e2e.sendCallbackQuery(`${intent}:skip_token`, flowUser)
    const skipId = await e2e.sendCallbackQuery(`${intent}:skip_token`, flowUserId)
    expect(skip[0]?.body?.text).toContain(`"message"`)
    expect(skipId[0]?.body?.text).toContain(`"message"`)
    e2e.clearCalls()
    const toggle = await e2e.sendCallbackQuery(`${intent}:toggle_view`, flowUser)
    const toggleId = await e2e.sendCallbackQuery(`${intent}:toggle_view`, flowUserId)
    expect(toggle[0]?.body?.text).toContain(`message`)
    expect(toggleId[0]?.body?.text).toContain(`message`)
  })
})
