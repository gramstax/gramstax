import {describe, it, expect, beforeEach} from "bun:test"
import {e2e, httpServerUrl} from "./setup"

const intent = `http-request`
beforeEach(() => {
  e2e.clearCalls()
})
describe(`E2E: HttpRequestPage`, () => {
  it(`show method selection`, async () => {
    await e2e.sendText(`/start`)
    e2e.clearCalls()
    const res = await e2e.sendCallbackQuery(intent)
    expect(res[0]!.body?.text).toBe(e2e.gmsg(intent, `s-method`, {}))
  })
  it(`show URL input after method selected`, async () => {
    await e2e.sendText(`/start`)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(intent)
    e2e.clearCalls()
    const res = await e2e.sendCallbackQuery(intent + `:GET`)
    expect(res.length).toBe(1)
    expect(res[0]!.body?.text).toBe(e2e.gmsg(intent, `s-url`, {method: `GET`}))
  })
  it(`makes HTTP request and shows response`, async () => {
    await e2e.sendText(`/start`)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(intent)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(intent + `:GET`)
    e2e.clearCalls()
    await e2e.sendText(httpServerUrl + `/test`)
    e2e.clearCalls()
    const res = await e2e.sendCallbackQuery(intent + `:skip_token`)
    expect(res.length).toBeGreaterThan(0)
    expect(res[0]!.body?.text).toContain(`[GET]`)
    expect(res[0]!.body?.text).toContain(`200`)
    expect(res[0]!.body?.text).toContain(`Hello from test server`)
  })
  it(`escapes HTML in response`, async () => {
    await e2e.sendText(`/start`)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(intent)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(intent + `:GET`)
    e2e.clearCalls()
    await e2e.sendText(httpServerUrl + `/html`)
    e2e.clearCalls()
    const res = await e2e.sendCallbackQuery(intent + `:skip_token`)
    expect(res[0]!.body?.text).toContain(`&lt;h1&gt;`)
    expect(res[0]!.body?.text).not.toContain(`<h1>`)
  })
  it(`shows invalid URL warning`, async () => {
    await e2e.sendText(`/start`)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(intent)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(intent + `:GET`)
    e2e.clearCalls()
    const res = await e2e.sendText(`not-a-valid-url`)
    expect(res[0]!.body?.text).toBe(e2e.gmsg(intent, `w-invalid`, {url: `not-a-valid-url`}))
  })
  it(`completes POST with body and echo`, async () => {
    await e2e.sendText(`/start`)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(intent)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(intent + `:POST`)
    e2e.clearCalls()
    await e2e.sendText(httpServerUrl + `/echo`)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(intent + `:skip_token`)
    e2e.clearCalls()
    const res = await e2e.sendText(`{"hello":"world"}`)
    expect(res[0]!.body?.text).toContain(`[POST]`)
    expect(res[0]!.body?.text).toContain(`echoed`)
  })
  it(`sends Bearer token in Authorization header`, async () => {
    await e2e.sendText(`/start`)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(intent)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(intent + `:GET`)
    e2e.clearCalls()
    await e2e.sendText(httpServerUrl + `/echo-headers`)
    e2e.clearCalls()
    const res = await e2e.sendText(`my-secret-token`)
    expect(res[0]!.body?.text).toContain(`[GET]`)
    expect(res[0]!.body?.text).toContain(`Bearer my-secret-token`)
  })
  it(`toggles between formatted and raw JSON`, async () => {
    await e2e.sendText(`/start`)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(intent)
    e2e.clearCalls()
    await e2e.sendCallbackQuery(intent + `:GET`)
    e2e.clearCalls()
    await e2e.sendText(httpServerUrl + `/test`)
    e2e.clearCalls()
    const skip = await e2e.sendCallbackQuery(intent + `:skip_token`)
    expect(skip[0]?.body?.text).toContain(`"message"`)
    e2e.clearCalls()
    const toggle = await e2e.sendCallbackQuery(intent + `:toggle_view`)
    expect(toggle[0]?.body?.text).toContain(`message`)
  })
})
